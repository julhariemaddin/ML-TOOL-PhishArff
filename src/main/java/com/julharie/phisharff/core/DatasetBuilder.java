package com.julharie.phisharff.core;

import com.julharie.phisharff.features.EmailFeatureExtractor;
import com.julharie.phisharff.features.FeatureExtractor;

import java.io.BufferedWriter;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.*;
import java.util.function.Consumer;

/**
 * The "Export" step. THE FLOW:
 *   1. drop rows with an unknown label (and, if asked, rows rated Invalid)
 *   2. remove duplicates, remove rows whose key has BOTH labels (conflicts)
 *   3. optionally balance the classes (same number of phishing and legitimate rows)
 *   4. shuffle (fixed seed 42, so the same input gives the same file)
 *   5. turn each row into numbers with the feature extractor and write the ARFF file
 */
public final class DatasetBuilder {
    public static final String VERSION = "1.0.0";
    private static final long SEED = 42L;

    private DatasetBuilder() {}

    public record Options(DataKind kind, boolean domainMode, boolean balance, boolean dropInvalid,
                          boolean hasSubject, boolean hasSender) {}

    public record Stats(int rowsIn, int unknownLabel, int invalidDropped, int duplicates, int conflicts,
                        int legitBefore, int phishingBefore, int rowsOut, int legitOut, int phishingOut,
                        List<String> featureNames) {}

    private record Row(Entry entry, boolean phishing) {}

    public record Built(List<Row> rows, Stats stats, Options options) {}

    // ---------------------------------------------------------------- steps 1-4
    public static Built build(List<Entry> entries, Options o) {
        int unknown = 0, invalidDropped = 0, dup = 0;
        Map<String, Row> unique = new LinkedHashMap<>();
        Set<String> conflicts = new HashSet<>();

        for (Entry e : entries) {
            String label = LabelNormalizer.normalize(e.label());
            if (label == null) { unknown++; continue; }
            Rating r = Keys.rate(o.kind(), e, o.hasSubject(), o.hasSender());
            if (r.level() == Rating.Level.INVALID && (o.dropInvalid() || r.score() == 0)) { invalidDropped++; continue; }

            boolean phishing = label.equals(LabelNormalizer.PHISHING);
            String key = Keys.of(o.kind(), e, o.domainMode());
            Row previous = unique.get(key);
            if (previous == null) unique.put(key, new Row(e, phishing));
            else if (previous.phishing() != phishing) conflicts.add(key);
            else dup++;
        }
        for (String key : conflicts) unique.remove(key);

        List<Row> legit = new ArrayList<>(), phish = new ArrayList<>();
        for (Row r : unique.values()) (r.phishing() ? phish : legit).add(r);
        int legitBefore = legit.size(), phishBefore = phish.size();

        Random rnd = new Random(SEED);
        Collections.shuffle(legit, rnd);
        Collections.shuffle(phish, rnd);
        if (o.balance()) {
            int n = Math.min(legit.size(), phish.size());
            legit = new ArrayList<>(legit.subList(0, n));
            phish = new ArrayList<>(phish.subList(0, n));
        }
        List<Row> all = new ArrayList<>(legit);
        all.addAll(phish);
        Collections.shuffle(all, rnd);

        List<String> names = o.kind() == DataKind.LINK
                ? FeatureExtractor.FEATURE_NAMES
                : EmailFeatureExtractor.featureNames(o.hasSubject(), o.hasSender());
        Stats stats = new Stats(entries.size(), unknown, invalidDropped, dup, conflicts.size(),
                legitBefore, phishBefore, all.size(), legit.size(), phish.size(), names);
        return new Built(all, stats, o);
    }

    // ---------------------------------------------------------------- step 5
    /** Writes the ARFF file and returns its SHA-256. */
    public static String writeArff(Built built, Path out, String sourceName, String sourceSha, Consumer<String> status)
            throws IOException {
        Options o = built.options();
        List<String> names = built.stats().featureNames();
        String mode = o.kind() == DataKind.LINK ? (o.domainMode() ? "domain" : "full") : "email";
        try (BufferedWriter w = Files.newBufferedWriter(out, StandardCharsets.UTF_8)) {
            w.write("% Generated by PhishArff " + VERSION + " (Julharie M. Maddin) on " + now() + "\n");
            w.write("% Source file: " + sourceName + "\n");
            w.write("% Source SHA-256: " + sourceSha + "\n");
            w.write("% Mode: " + mode + "\n\n");
            w.write("@relation phisharff_" + o.kind().plural() + "\n\n");
            for (String n : names) w.write("@attribute " + n + " numeric\n");
            w.write("@attribute class {" + LabelNormalizer.LEGIT + "," + LabelNormalizer.PHISHING + "}\n\n@data\n");

            int done = 0;
            for (Row r : built.rows()) {
                double[] f = features(r.entry(), o);
                StringBuilder sb = new StringBuilder();
                for (double v : f) sb.append(fmt(v)).append(',');
                sb.append(r.phishing() ? LabelNormalizer.PHISHING : LabelNormalizer.LEGIT).append('\n');
                w.write(sb.toString());
                if (++done % 5000 == 0) status.accept("Writing rows... " + done);
            }
        }
        return Checksum.sha256(out);
    }

    /** A plain-text report written next to the ARFF file, so the result can be reproduced and cited. */
    public static void writeInfo(Built built, Path infoFile, String sourceName, String sourceSha, String arffSha)
            throws IOException {
        Stats s = built.stats();
        Options o = built.options();
        StringBuilder sb = new StringBuilder();
        sb.append("PhishArff ").append(VERSION).append(" - export report\n");
        sb.append("Author: Julharie M. Maddin (ORCID 0009-0009-3366-1271)\n");
        sb.append("Created: ").append(now()).append("\n\n");
        sb.append("Data type : ").append(o.kind().title()).append("\n");
        if (o.kind() == DataKind.LINK) sb.append("Mode      : ").append(o.domainMode() ? "domain (host only)" : "full URL").append("\n");
        else sb.append("Columns   : body").append(o.hasSubject() ? ", subject" : "").append(o.hasSender() ? ", sender" : "").append("\n");
        sb.append("Source    : ").append(sourceName).append("\nSource SHA-256: ").append(sourceSha).append("\n");
        sb.append("ARFF SHA-256  : ").append(arffSha).append("\n\n");
        sb.append("Rows read: ").append(s.rowsIn()).append("\n");
        sb.append("  unknown label dropped : ").append(s.unknownLabel()).append("\n");
        sb.append("  invalid rows dropped  : ").append(s.invalidDropped()).append("\n");
        sb.append("  duplicates removed    : ").append(s.duplicates()).append("\n");
        sb.append("  conflicting keys removed (both labels): ").append(s.conflicts()).append("\n");
        sb.append("  before balancing: legitimate ").append(s.legitBefore()).append(", phishing ").append(s.phishingBefore()).append("\n");
        sb.append("Rows written: ").append(s.rowsOut()).append(" (legitimate ").append(s.legitOut())
                .append(", phishing ").append(s.phishingOut()).append(")  balanced=").append(o.balance()).append("\n");
        sb.append("Shuffle seed: ").append(SEED).append("\n\n");
        sb.append("Label mapping: benign/legit/good/safe/ham/0 = legitimate; phishing/malicious/bad/spam/scam/1 = phishing\n\n");
        sb.append("Features (column order):\n");
        int i = 1;
        for (String n : s.featureNames()) sb.append(String.format("  %2d. %s%n", i++, n));
        Files.writeString(infoFile, sb.toString(), StandardCharsets.UTF_8);
    }

    static double[] features(Entry e, Options o) {
        if (o.kind() == DataKind.LINK) {
            String url = e.url() == null ? "" : e.url();
            return o.domainMode() ? FeatureExtractor.extractDomainLevel(url) : FeatureExtractor.extract(url);
        }
        return EmailFeatureExtractor.extract(o.hasSubject() ? nz(e.subject()) : null,
                o.hasSender() ? nz(e.sender()) : null, nz(e.body()));
    }

    private static String nz(String s) { return s == null ? "" : s; }

    /** 56.0 -> "56", 0.1071428 -> "0.107143". */
    static String fmt(double v) {
        if (v == Math.rint(v) && Math.abs(v) < 1e15) return Long.toString((long) v);
        String s = String.format(Locale.ROOT, "%.6f", v);
        int end = s.length();
        while (s.charAt(end - 1) == '0') end--;
        return s.substring(0, end);
    }

    private static String now() {
        return LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm"));
    }
}
