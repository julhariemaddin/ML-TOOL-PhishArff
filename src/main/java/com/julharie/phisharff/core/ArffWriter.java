package com.julharie.phisharff.core;

import com.julharie.phisharff.core.DatasetBuilder.Built;
import com.julharie.phisharff.core.DatasetBuilder.Options;
import com.julharie.phisharff.core.DatasetBuilder.Row;
import com.julharie.phisharff.features.EmailFeatureExtractor;
import com.julharie.phisharff.features.FeatureConfig;
import com.julharie.phisharff.features.FeatureExtractor;

import java.io.BufferedWriter;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.Locale;
import java.util.Map;
import java.util.TreeMap;
import java.util.function.Consumer;

/**
 * The "Export" step, part 2: writes the ARFF file.
 *
 *   dense  (no n-grams):   56,29,6,...,3,phishing
 *   sparse (n-gram on):    {0 56,1 29,...,40 3,812 1,26+buckets phishing}   (only non-zero columns, ascending)
 *
 * Weka reads both. Sparse keeps files small when thousands of n-gram columns are mostly zero.
 */
final class ArffWriter {
    private ArffWriter() {}

    /** Writes the file and returns its SHA-256. */
    static String write(Built built, Path out, String sourceName, String sourceSha, Consumer<String> status)
            throws IOException {
        Options o = built.options();
        try (BufferedWriter w = Files.newBufferedWriter(out, StandardCharsets.UTF_8)) {
            writeHeader(w, built, sourceName, sourceSha);
            int done = 0;
            for (Row r : built.rows()) {
                w.write(row(r, o));
                if (++done % 5000 == 0) status.accept("Writing rows... " + done);
            }
        }
        return Checksum.sha256(out);
    }

    private static void writeHeader(BufferedWriter w, Built built, String sourceName, String sourceSha) throws IOException {
        Options o = built.options();
        String mode = o.kind() == DataKind.LINK ? (o.domainMode() ? "domain" : "full") : "email";
        w.write("% Generated by PhishArff " + DatasetBuilder.VERSION + " (Julharie M. Maddin) on " + now() + "\n");
        w.write("% Source file: " + sourceName + "\n");
        w.write("% Source SHA-256: " + sourceSha + "\n");
        w.write("% Mode: " + mode + "\n");
        if (o.ngrams()) w.write("% N-grams: " + o.ngramBuckets() + " hashed columns, host only, sizes "
                + FeatureExtractor.NGRAM_MIN + "-" + FeatureExtractor.NGRAM_MAX + " (sparse format)\n");
        w.write("\n@relation phisharff_" + o.kind().plural() + "\n\n");
        for (String n : built.stats().featureNames()) w.write("@attribute " + n + " numeric\n");
        if (o.ngrams()) {
            for (int i = 0; i < o.ngramBuckets(); i++) w.write("@attribute " + FeatureExtractor.ngramName(i) + " numeric\n");
        }
        w.write("@attribute class {" + LabelNormalizer.LEGIT + "," + LabelNormalizer.PHISHING + "}\n\n@data\n");
    }

    /** One data line, including the line break. */
    static String row(Row r, Options o) {
        String cls = r.phishing() ? LabelNormalizer.PHISHING : LabelNormalizer.LEGIT;
        if (o.kind() == DataKind.LINK) {
            String url = r.entry().url() == null ? "" : r.entry().url();
            FeatureConfig cfg = o.featureConfig();
            double[] base = cfg.domainMode() ? FeatureExtractor.extractDomainLevel(url) : FeatureExtractor.extract(url);
            return cfg.ngrams()
                    ? sparseRow(base, FeatureExtractor.ngramCounts(url, cfg.ngramBuckets()), cfg.ngramBuckets(), cls)
                    : denseRow(base, cls);
        }
        double[] f = EmailFeatureExtractor.extract(o.hasSubject() ? nz(r.entry().subject()) : null,
                o.hasSender() ? nz(r.entry().sender()) : null, nz(r.entry().body()));
        return denseRow(f, cls);
    }

    static String denseRow(double[] values, String cls) {
        StringBuilder sb = new StringBuilder();
        for (double v : values) sb.append(fmt(v)).append(',');
        return sb.append(cls).append('\n').toString();
    }

    /** {column value, ..., classColumn className}. Zeros are left out; the class is always written. */
    static String sparseRow(double[] base, TreeMap<Integer, Integer> ngrams, int buckets, String cls) {
        StringBuilder sb = new StringBuilder("{");
        boolean first = true;
        for (int i = 0; i < base.length; i++) {
            if (base[i] == 0.0) continue;
            if (!first) sb.append(',');
            sb.append(i).append(' ').append(fmt(base[i]));
            first = false;
        }
        for (Map.Entry<Integer, Integer> e : ngrams.entrySet()) {
            if (!first) sb.append(',');
            sb.append(base.length + e.getKey()).append(' ').append(e.getValue());
            first = false;
        }
        if (!first) sb.append(',');
        return sb.append(base.length + buckets).append(' ').append(cls).append("}\n").toString();
    }

    private static String nz(String s) { return s == null ? "" : s; }

    /** 56.0 -> "56", 0.1071428 -> "0.107143". */
    static String fmt(double v) {
        if (v == Math.rint(v) && Math.abs(v) < 1e15) return Long.toString((long) v);
        String s = String.format(Locale.ROOT, "%.6f", v);
        int end = s.length();
        while (s.charAt(end - 1) == '0') end--;
        return s.substring(0, end);
    }

    static String now() {
        return LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm"));
    }
}
